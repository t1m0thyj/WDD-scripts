    Set-ItemProperty -Path $settingsKey -Name Data -Value $newData -Type Binary
    if (Test-Path $stateKey) {
        Set-ItemProperty -Path $stateKey -Name Data -Value ([byte[]](0x02,0x00,0x00,0x00,0x3A,0xA1,0x5C,0xDC,0x51,0xD6,0xD7,0x01,0x00,0x00,0x00,0x00,0x43,0x42,0x01,0x00,0x0A,0x00,0x00,0x00,0x0A,0x00,0x00,0x00)) -Type Binary
