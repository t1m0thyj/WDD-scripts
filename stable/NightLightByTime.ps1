# WinDynamicDesktop script: enable Night Light after 22:00
# Install in WDD: Settings -> Scripts -> Install from file

# ===== НАСТРОЙКИ =====
$nightTime = "22:00"   # с этого времени включать Night Light
$dayTime   = "06:00"   # с этого времени выключать (утром)
# =====================

$params = $Input | ConvertFrom-Json

$now   = Get-Date
$night = [datetime]::ParseExact($nightTime, "HH:mm", $null).TimeOfDay
$day   = [datetime]::ParseExact($dayTime,   "HH:mm", $null).TimeOfDay
$t = $now.TimeOfDay

$wantNight = ($t -ge $night -or $t -lt $day)

$base = "HKCU:\Software\Microsoft\Windows\CurrentVersion\CloudStore\Store\DefaultAccount\Current\default"
$settingsKey = "$base\`$windows.data.bluelightreduction.settings\`$windows.data.bluelightreduction.settings"
$stateKey    = "$base\`$windows.data.bluelightreduction.bluelightreductionstate\`$windows.data.bluelightreduction.bluelightreductionstate"

if (-not (Test-Path $settingsKey)) {
    # Night Light ни разу не включали вручную — включить один раз в Параметрах и перезапустить скрипт
    exit
}

# Включён ли сейчас Night Light: в blob settings байт по индексу 18 == 0x15
$data = (Get-ItemProperty -Path $settingsKey -Name Data).Data
$currentlyOn = ($data[18] -eq 0x15)

if ($currentlyOn -eq $wantNight) { exit }  # уже как надо

if ($wantNight) {
