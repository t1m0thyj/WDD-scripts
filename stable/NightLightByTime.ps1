    # выключить: усечённый blob "Disabled"
    $offData = [byte[]](0x02,0x00,0x00,0x00,0x1E,0x55,0xC0,0x64,0x08,0x06,0xD8,0x01,0x00,0x00,0x00,0x00,
                        0x43,0x42,0x01,0x00,0x01,0x00,0x00,0x00)
    Set-ItemProperty -Path $settingsKey -Name Data -Value $offData -Type Binary
    if (Test-Path $stateKey) { Remove-ItemProperty -Path $stateKey -Name Data -ErrorAction SilentlyContinue }
}

